class Context:
    """The manifests, and the source revisions, a rule may compare a row with."""

    def __init__(
        self,
        committed: Manifest,
        regenerated: Manifest,
        parity: Manifest | None,
        sources: SourceTexts | None = None,
        baseline_observation: Manifest | None = None,
    ) -> None:
        self.committed = committed
        self.regenerated = regenerated
        self.parity = parity
        self.sources = sources
        self.baseline_observation = baseline_observation
        self.workspace_source_guards_valid: bool | None = None

    @staticmethod
    def same_site(manifest: Manifest | None, row: Row) -> list[Row]:
        return manifest.by_site.get(row.site, []) if manifest is not None else []


@dataclasses.dataclass(frozen=True)
class Rule:
    name: str
    lane: str
    side: str  # "+" explains an added row, "-" a removed one, "+-" either
    summary: str
    predicate: Callable[[Row, str, Context], bool]

    def matches(self, row: Row, side: str, context: Context) -> bool:
        return side in self.side and self.predicate(row, side, context)


def workspace_source_guards_match(context: Context) -> bool:
    if context.workspace_source_guards_valid is not None:
        return context.workspace_source_guards_valid

    sources = context.sources

    def matches(text: str | None, expected: str) -> bool:
        return text is not None and hashlib.sha256(text.encode("utf-8")).hexdigest() == expected

    valid = sources is not None and all(
        matches(sources.base(path), digest) for path, digest in WORKSPACE_LEASE_BASE_SOURCE_SHA256.items()
    ) and all(
        matches(sources.head(path), digest) and matches(sources.base(path), digest)
        for path, digest in WORKSPACE_LEASE_TERMINAL_SOURCE_SHA256.items()
    )

    context.workspace_source_guards_valid = valid

    return valid


def is_reviewed_workspace_lease_closure(row: Row, side: str, context: Context, pin_cleanup: bool) -> bool:
    # Observation membership establishes a checker addition, not a passing baseline qualification. The exact reviewed footprint
    # and source guards bind its mechanism; no diagnostic, source prefix, or missing frontier grants an explanation.
    return (
        side == "+"
        and context.parity is not None
        and context.baseline_observation is not None
        and row in context.parity.counter
        and row not in context.baseline_observation.counter
        and row not in context.committed.counter
        and row in WORKSPACE_LEASE_REVIEWED_ROWS
        and (row.source_path.endswith("/Coordination/RetainedExclusiveFileLock.cs")) == pin_cleanup
        and workspace_source_guards_match(context)
    )


def is_interceptor_callback(row: Row, side: str, context: Context) -> bool:
    return row.enclosing_type in INTERCEPTOR_CALLBACK_TYPES


def is_slot_dispatch(row: Row, side: str, context: Context) -> bool:
    return row.enclosing_type in SLOT_DISPATCH_TYPES


def is_base_constructor(row: Row, side: str, context: Context) -> bool:
    """The base constructor of a subclass the table lists, at the member the table lists, with the source declaring the subclass."""
    if row.kind not in ("FileSystemEffect", "FileSystemRead") or context.sources is None:
        return False

    for entry in BASE_CONSTRUCTOR_SITES:
        if (row.source_path, row.member, row.callee) != (entry.source_path, entry.member, f"System.IO.{entry.base}..ctor"):
            continue

        member_text = context.sources.head(entry.source_path)
        declaring_text = context.sources.head(entry.declared_in)

        if member_text is None or declaring_text is None:
            continue

        derives = re.search(
            r"\bclass\s+" + re.escape(entry.subclass) + r"\s*(?:\([^)]*\))?\s*:\s*(?:System\.IO\.)?" + entry.base + r"\b",
            declaring_text,
        )

        if derives and re.search(r"\b" + re.escape(entry.subclass) + r"\b", "\n".join(member_bodies(member_text, entry.member))):
            return True

    return False


def is_in_memory_stream_base_constructor(row: Row, side: str, context: Context) -> bool:
    """Only the exact reviewed old-source rows, removed by checker parity over the pinned source declarations."""
    if (
        row not in IN_MEMORY_STREAM_BASE_CONSTRUCTOR_REMOVALS
        or context.parity is None
        or context.sources is None
        or context.same_site(context.parity, row)
    ):
        return False

    for path, digest in IN_MEMORY_STREAM_BASE_SOURCES.items():
        text = context.sources.base(path)

        if text is None or hashlib.sha256(text.encode("utf-8")).hexdigest().upper() != digest:
            return False

    return True


def withdraws_effect(row: Row, side: str, context: Context) -> bool:
    """The checker keeps the site and its Work and takes the Effect away, or drops the group site whose Effect it would grant."""
    if side == "-":
        partners = context.same_site(context.parity, row)

        if row.kind == "EffectFrontier" and row.callee.endswith(GROUP_CALLEE_SUFFIX) and context.parity is not None and not partners:
            return True

        return row.effect != "-" and any(partner.work == row.work and partner.registered_root_work == row.registered_root_work and partner.effect == "-" for partner in partners)

    return row.effect == "-" and any(
        partner.work == row.work and partner.registered_root_work == row.registered_root_work and partner.effect != "-" for partner in context.same_site(context.committed, row)
    )


def is_stream_disposal_by_origin(row: Row, side: str, context: Context) -> bool:
    """The disposal of a stream the checker now resolves to the exact in-memory or database stream it came from.

    The parity traversal no longer has the row, and the member's own source declares an in-memory or a database stream and
    touches no file-backed one, so the abstract Stream.Dispose the checker assumed before has nothing left to be a file effect of.
    """
    if (
        row.kind != "FileSystemEffect"
        or row.callee != STREAM_DISPOSE
        or context.parity is None
        or context.sources is None
        or context.same_site(context.parity, row)
    ):
        return False

    text = context.sources.head(row.source_path)

    bodies = member_bodies(text, row.member) if text is not None else []

    return any(
        any(pattern.search(body) for pattern in IN_MEMORY_STREAM_USINGS) and not FILE_BACKED_STREAM.search(body) for body in bodies
    )


def physical_work_root_separation(row: Row, side: str, context: Context) -> bool:
    if context.committed.version != 1 or context.parity is None or context.parity.version != 2:
        return False

    old_rows = [row] if side == "-" else context.same_site(context.committed, row)
    new_rows = [row] if side == "+" else context.same_site(context.parity, row)
    declared_kinds = {"GuildMaintenance", "SagaExtraction", "SessionAttachmentIndexing", "LoremasterSummarization"}

    for old in old_rows:
        for new in new_rows:
            if (new not in context.parity.counter or old not in context.committed.counter or old.site != new.site
                or old.work == "-" or new.work in ("-", old.work) or new.registered_root_work != old.work
                or new.admitted_work_kind != old.admitted_work_kind
                or new.effect not in (old.effect, "-") or unresolved_references(context.parity, new)):
                continue
            physical = [x for x in context.parity.resolve(new.work) if x.root == new.root
                        and x.kind == "EffectFrontier" and x.admitted_work_kind == "GuildStorage"]
            declared = [x for x in context.parity.resolve(new.registered_root_work) if x.root == new.root
                        and x.kind == "EffectFrontier" and x.admitted_work_kind in declared_kinds]
            if physical and declared:
                return True
    return False


