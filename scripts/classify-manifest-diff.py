    added_unframed = sorted(row for row in unframed(regenerated) - unframed(committed) if selection_root(row) not in new_root_keys)

    long_rest_unframed = [row for row in unframed(regenerated) if is_long_rest_root(row.root)]

    reviewed = {(entry.root_type, entry.operation) for entry in UNFRAMED_PROVIDER_CALL_ROOTS}

    unreviewed_unframed = sorted(row for row in unframed(regenerated) if selection_root(row) not in reviewed)

    # No ProviderCall row goes away unexplained: its own file was edited, a rule explains it, or a row with both frames replaced it.
    replaced_sites = {
        item.row.site
        for item in (labelled or [])
        if item.side == "+" and item.row.kind == "ProviderCall" and "-" not in (item.row.work, item.row.effect)
    }

    vanished_provider_calls = [
        item.row
        for item in (labelled or [])
        if item.side == "-" and item.row.kind == "ProviderCall" and item.label not in ("a", "c") and item.row.site not in replaced_sites
    ]

    old_roots = {row.root for row in committed.rows}
    new_roots = {row.root for row in regenerated.rows}

    foreign_new_roots = sorted(
        root
        for root in new_roots - old_roots
        if not is_long_rest_root(root) and (root[0], root[1].split("~")[0]) not in new_root_keys
    )

    lost_roots = sorted(old_roots - new_roots)

    formals = [row for row in regenerated.rows if row.kind == "EffectFrontier" and row.callee.endswith(".IGrimoireWorkLease.RootLeaseFormal")]

    bound_roots = {row.callee for row in regenerated.rows if row.kind == "LeaseHandoff"}

    unbound = sorted({row.root for row in formals if row.authority_operation_id not in bound_roots})

    # The Long Rest worker admits its kind where it acquires or is handed the lease, and only the root it hands the lease to
    # (the one with a Root Lease Formal row) reaches the provider.
    handoff_roots = {row.root for row in formals if is_long_rest_root(row.root)}

    long_rest_structure = [
        f"{row.root_type}|{row.authority_operation_id}|{row.callee}: admitted kind {row.admitted_work_kind}"
        for row in regenerated.rows
        if is_long_rest_root(row.root)
        and row.kind == "EffectFrontier"
        and (row.callee.endswith(".TryAcquireWorkLease") or row.callee.endswith(".IGrimoireWorkLease.RootLeaseFormal"))
        and row.admitted_work_kind != "LongRestSweep"
    ] + [
        f"{row.root_type}|{row.authority_operation_id}|{row.callee}: a provider call outside the handoff root"
        for row in regenerated.rows
        if is_long_rest_root(row.root) and row.kind == "ProviderCall" and row.root not in handoff_roots
    ]

    def describe(row: Row) -> str:
        return f"{row.root_type}|{row.authority_operation_id}|{row.callee}|{row.member}"

    return [
        Invariant(
            "provider-call-frames",
            "no ProviderCall row is added without a Work and an Effect capsule, the ones that have neither sit under the reviewed "
            "roots, and the Long Rest roots hold none",
            [describe(row) for row in added_unframed]
            + [describe(row) for row in long_rest_unframed]
            + [describe(row) + ": under no reviewed root" for row in unreviewed_unframed],
        ),
        Invariant(
            "provider-call-removals",
            "no ProviderCall row is removed unless its own file was edited, a named rule explains it or a framed row replaces it",
            [describe(row) for row in vanished_provider_calls],
        ),
        Invariant(
            "new-roots",
            "a root the committed manifest did not have is a Long Rest root or one NEW_ROOTS names",
            [f"{root[0]}|{root[1]}" for root in foreign_new_roots],
        ),
        Invariant(
            "kept-roots",
            "every root of the committed manifest still has rows",
            [f"{root[0]}|{root[1]}" for root in lost_roots],
        ),
        Invariant(
            "long-rest-structure",
            "the Long Rest roots admit the Long Rest kind and only the handoff root reaches a provider",
            long_rest_structure,
        ),
        Invariant(
            "handoff-binding",
            "every Root Lease Formal row names a root that a Lease-Handoff binding row ties to its caller",
            [f"{root[0]}|{root[1]}" for root in unbound],
        ),
    ]


