def selection_root(row: Row) -> tuple[str, str]:
    """A selection root names its call and then the digest of the selected source after a tilde; the manifest pins the digest."""
    return (row.root_type, row.authority_operation_id.split("~")[0])


def describe(row: Row) -> str:
    return f"{row.root_type}|{row.authority_operation_id}|{row.callee}|{row.member}"


def joined_guild_authorization_violations(manifest: Manifest) -> list[str]:
    """Require the reviewed joined call and the canonical child's independently acquired Work."""
    links = [row for row in manifest.rows if row.kind == "JoinedSelfAdmission"]
    child = [row for row in manifest.rows if row.root == JOINED_GUILD_AUTHORIZER]
    violations: list[str] = []

    if bool(links) != bool(child):
        violations.append("the joined Guild authorization root and its caller links must both be present")

    caller_roots = {row.root for row in manifest.rows if row.kind != "JoinedSelfAdmission"}
    link_counts = collections.Counter(row.root for row in links)
    for row in links:
        if (row.root == JOINED_GUILD_AUTHORIZER or row.root not in caller_roots or link_counts[row.root] != 1
                or row.callee != JOINED_GUILD_AUTHORIZER[1] or row.capsule_id != JOINED_GUILD_AUTHORIZER_LINK
                or row.references or row.admitted_work_kind != "-"):
            violations.append(describe(row) + ": not an exact joined Guild revalidation call in its caller root without a borrowed frontier")

    own_work = collections.Counter(row.capsule_id for row in child
        if row.kind == "EffectFrontier" and row.callee == JOINED_GUILD_WORK_ACQUISITION
        and row.work == row.registered_root_work == row.capsule_id
        and row.admitted_work_kind == "GuildStorage" and row.effect == "-")

    for row in child:
        allowed = (row.kind == "FileSystemRead"
            or row.kind == "DatabaseAccess" and row.callee in JOINED_GUILD_DATABASE_CALLEES
            or row.kind == "OrdinaryConnectionRoute" and row.callee == JOINED_GUILD_CONNECTION_ROUTE
            or row.kind == "EffectFrontier" and own_work[row.capsule_id] == 1)

        if (not allowed or row.effect != "-" or row.work != row.registered_root_work
                or own_work[row.work] != 1 or unresolved_references(manifest, row)):
            violations.append(describe(row) + ": canonical Guild authorization requires its own exact GuildStorage Work and reviewed site kinds")

    return violations


def reviewed_new_root_keys(manifest: Manifest) -> set[tuple[str, str]]:
    roots = {(entry.root_type, entry.operation) for entry in NEW_ROOTS}
    if any(row.root == JOINED_GUILD_AUTHORIZER for row in manifest.rows) and not joined_guild_authorization_violations(manifest):
        roots.add(JOINED_GUILD_AUTHORIZER)
    return roots


def check_invariants(committed: Manifest, regenerated: Manifest, labelled: list[Labelled] | None = None,
                     parity: Manifest | None = None) -> list[Invariant]:
    """The facts about a regeneration that hold whatever its rows are labelled."""

    def unframed(manifest: Manifest) -> set[Row]:
        return {row for row in manifest.rows if row.kind == "ProviderCall" and "-" in (row.work, row.effect)}

    # A lifecycle, maintenance or request root is judged without a Work frontier by design, so the committed manifest already holds
    # unframed ProviderCall rows. They sit under the reviewed roots, the regeneration must not add one, and the Long Rest roots,
    # which are ordinary hosted work, must hold none.
    # A reviewed new root the committed manifest does not hold yet has no rows to compare with, so every row it holds is added; its
    # unframed ProviderCall rows are held to the reviewed list below instead of to the committed manifest. The exemption ends with the
    # regeneration that commits the root: once the committed manifest holds it, an unframed row it gains is held to the committed
    # manifest like the row of any other root.
    new_root_keys = reviewed_new_root_keys(regenerated)

    old_roots = {row.root for row in committed.rows}

    if committed.version == 1 and regenerated.version == 2:
        # A v1 omitted field is unknown, not an explicit v2 '-'. Consume each old and
        # exact, unambiguous parity occurrence at most once for an unchanged new row.
        old_budget = collections.Counter(tuple(row[:13]) for row in committed.rows
                                         if row.kind == "ProviderCall" and "-" in (row.work, row.effect))
        parity_budget = parity.counter.copy() if parity is not None and parity.version == 2 else collections.Counter()
        parity_refinements: dict[tuple[str, ...], set[Row]] = collections.defaultdict(set)
        if parity is not None and parity.version == 2:
            for candidate in parity.rows:
                parity_refinements[tuple(candidate[:13])].add(candidate)
        additions = []
        for row in regenerated.rows:
            if row.kind != "ProviderCall" or "-" not in (row.work, row.effect):
                continue
            key = tuple(row[:13])
            if (old_budget[key] > 0 and parity_budget[row] > 0 and parity_refinements[key] == {row}
                and not unresolved_references(parity, row) and not unresolved_references(regenerated, row)):
                old_budget[key] -= 1
                parity_budget[row] -= 1
            else:
                additions.append(row)
    else:
        old_unframed = collections.Counter(row for row in committed.rows if row.kind == "ProviderCall" and "-" in (row.work, row.effect))
        new_unframed = collections.Counter(row for row in regenerated.rows if row.kind == "ProviderCall" and "-" in (row.work, row.effect))
        additions = list((new_unframed - old_unframed).elements())

    added_unframed = sorted(
        row for row in additions
        if not (selection_root(row) in new_root_keys and row.root not in old_roots)
    )

    long_rest_unframed = [row for row in unframed(regenerated) if is_long_rest_root(row.root)]

    reviewed = {(entry.root_type, entry.operation) for entry in UNFRAMED_PROVIDER_CALL_ROOTS}

    unreviewed_unframed = sorted(row for row in unframed(regenerated) if selection_root(row) not in reviewed)

    # A removed ProviderCall needs edited ownership, an exact retired call chain, a named rule or a framed replacement.
    replaced_sites = {
        item.row.site
        for item in (labelled or [])
        if item.side == "+" and item.row.kind == "ProviderCall" and "-" not in (item.row.work, item.row.effect)
    }

    vanished_provider_calls = [
        item.row
        for item in (labelled or [])
        if item.side == "-" and item.row.kind == "ProviderCall" and item.label not in ("a", "c", "v1-provenance")
        and (item.label != "r" or item.rule != RETIRED_SOURCE_REACH_RULE)
        and item.row.site not in replaced_sites
    ]

    new_roots = {row.root for row in regenerated.rows}

    foreign_new_roots = sorted(
        root
        for root in new_roots - old_roots
        if not is_long_rest_root(root) and (root[0], root[1].split("~")[0]) not in new_root_keys
    )

    lost_roots = sorted(old_roots - new_roots)

    formals = [row for row in regenerated.rows if row.kind == "EffectFrontier" and row.callee.endswith(".IGrimoireWorkLease.RootLeaseFormal")]

    bound_roots = {row.callee for row in regenerated.rows if row.kind == "LeaseHandoff"}

    unbound = sorted({row.root for row in formals if row.authority_operation_id not in bound_roots})

    # The Long Rest worker admits its kind where it acquires or is handed the lease, and only the root it hands the lease to
    # (the one with a Root Lease Formal row) reaches the provider.
    handoff_roots = {row.root for row in formals if is_long_rest_root(row.root)}

    long_rest_structure = [
        f"{row.root_type}|{row.authority_operation_id}|{row.callee}: admitted kind {row.admitted_work_kind}"
        for row in regenerated.rows
        if is_long_rest_root(row.root)
        and row.kind == "EffectFrontier"
        and (row.callee.endswith(".TryAcquireWorkLease") or row.callee.endswith(".IGrimoireWorkLease.RootLeaseFormal"))
        and row.admitted_work_kind != "LongRestSweep"
    ] + [
        f"{row.root_type}|{row.authority_operation_id}|{row.callee}: a provider call outside the handoff root"
        for row in regenerated.rows
        if is_long_rest_root(row.root) and row.kind == "ProviderCall" and row.root not in handoff_roots
    ]

    return [
        Invariant(
            "provider-call-frames",
            "unframed ProviderCall additions require a reviewed root and exact admitted Effect witness; "
            "the Long Rest roots hold none",
            [describe(row) for row in added_unframed]
            + [describe(row) for row in long_rest_unframed]
            + [describe(row) + ": under no reviewed root" for row in unreviewed_unframed],
        ),
        Invariant(
            "provider-call-removals",
            "no ProviderCall row is removed unless its own file was edited, its exact call chain was retired, a named rule explains it or a framed row replaces it",
            [describe(row) for row in vanished_provider_calls],
        ),
        Invariant(
            "new-roots",
            "a root the committed manifest did not have is a Long Rest root or one NEW_ROOTS names",
            [f"{root[0]}|{root[1]}" for root in foreign_new_roots],
        ),
        Invariant(
            "kept-roots",
            "every root of the committed manifest still has rows",
            [f"{root[0]}|{root[1]}" for root in lost_roots],
        ),
        Invariant(
            "long-rest-structure",
            "the Long Rest roots admit the Long Rest kind and only the handoff root reaches a provider",
            long_rest_structure,
        ),
        Invariant(
            "joined-guild-authorization",
            "the exact joined caller binds the Guild authorizer with its own GuildStorage Work and no external effects",
            joined_guild_authorization_violations(regenerated),
        ),
        Invariant(
            "handoff-binding",
            "every Root Lease Formal row names a root that a Lease-Handoff binding row ties to its caller",
            [f"{root[0]}|{root[1]}" for root in unbound],
        ),
    ]


