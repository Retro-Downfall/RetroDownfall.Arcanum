#!/usr/bin/env python3
"""The Diff Row Classifier for the reviewed hosted-producer capsule manifest.

The manifest (tests/RetroDownfall.Arcanum.Tests/Support/hosted-grimoire-producer-capsules-v2.tsv) is regenerated by the production
discovery with ARCANUM_UPDATE_HOSTED_PRODUCER_CAPSULES=1. A regeneration is reviewed, not trusted: every row it adds or removes
must be explained, and this script labels each one.

  python3 scripts/classify-manifest-diff.py --committed OLD.tsv --regenerated NEW.tsv --git-base b15d6960 [--git-head HEAD] [--repo .]
                            [--edited-sources FILE] [--parity PARITY.tsv] [--baseline-observation BASELINE.tsv] [--report OUT.tsv] [--json OUT.json]

Input
  --committed     the manifest before the regeneration
  --regenerated   the manifest after it
  --git-base/--git-head/--repo
                  the source files changed since the base (git diff --name-only BASE HEAD -- src); --edited-sources FILE
                  reads the same list from a file, one path per line. --git-base also lets the script read a source file at
                  the two revisions, which the class r and the rules that read the source need; without it they explain nothing.
  --parity        optional. The manifest the same checker renders over the BASE source (the Old-Source Parity run: the
                  candidate checker with src/ swapped back to the base). It establishes the source/checker comparison stage
                  (see "Stages"); an exact baseline observation distinguishes historical ledger omissions from checker additions.

  --baseline-observation
                  optional exact baseline-checker/baseline-source manifest. Together with --parity, exact added rows already
                  discovered by that baseline are historical ledger omissions, not checker-caused changes. Its diagnostic report
                  is retained separately; supplying it never establishes a passing baseline qualification.

A row is one site seen from one root: (root_type, authority_operation_id) is the root, the next eight columns are the site, and
the last four are the site's frame (its physical Work capsule, Effect capsule, admitted work kind and explicit registered-root Work witness). Historical v1 inputs carry no registered-root witness. A frame column holds the
capsule id of the acquisition or group site it names, and a capsule id is the SHA-256 of the site's own columns, so every
reference resolves inside the manifest that carries it. A row changed by the regeneration is a removed row and an added row that
share their site.

Classes (the first that applies, except exact call retirement is tested ahead of a and b)
  v1-provenance  a v1 row with unknown registered-root Work pairs through its unique exact resolved v2 parity witness
  b-format  the added and the removed row are equal once the "@lease:<origin>" marker an Effect id carries is normalised away
  l         an added complete row absent from the committed ledger appears exactly in both --baseline-observation and --parity:
            pre-existing discovery omitted from that ledger, not a checker-caused change or a qualified baseline
  n         the row belongs to a root the committed manifest did not have and NEW_ROOTS names: every row of a reviewed new root
            is that root's, whichever source it comes from, so the root is what is reviewed and not its rows one by one
  a         the row's own site is in an edited source
  b         its physical Work, Effect or registered-root Work reference resolves to an edited acquisition, group or formal,
            in its own manifest or that of the row paired by site
  r         with --parity, the source alone introduced or removed the row, its site and frames are all in unedited sources,
            and a REACHED_THROUGH entry names the edited call that reaches it: the entry's caller is an edited source whose text
            gained (for an added row) or lost (for a removed one) the entry's marker between the base and the head. A row of
            this kind with no entry, or whose marker did not change, is d: the tool does not infer a call chain.
            The retired budget paths pin the complete removed row and the former and replacement calls in one edited member.
            Where parity is supplied this exact retirement proof also requires a source-stage removal.
  c         introduced or removed by a named checker rule of this branch: the row matches the mechanical predicate of one rule in
            RULES below (with --parity, only a row that the checker alone introduced or removed is tested, and it is tested
            before any source class, so a row of an edited file that the checker yields over the unchanged base source is
            not credited to the edit)
  d         UNEXPLAINED. The review requires zero.

Stages (only with --parity). P is the manifest of the new checker over the base source, C the committed manifest and N the
regenerated one. N and P share a checker, so a row in N and not in P is source-derived. P and C share a source, but C may omit
pre-existing baseline discovery: additions in P enter the checker comparison stage until an exact baseline observation B
separates those omissions. An added complete row already in both B and P is labelled l with stage baseline-ledger before
source/checker attribution. Other added rows in P remain in the checker stage; additions outside P are source-derived. Removed
rows absent from P enter the checker stage and other removals the source stage. Without --parity the exact retirement proof
is still available, followed by the classes a, b and c. A source call-chain change without exact retirement remains unexplained.

The rules (see RULES; each names the DESIGN paragraph that states its lane)
  workspace-lease-closed-dispatch           exact reviewed workspace lease validation/recovery and downstream store/read closure
  retained-workspace-pin-cleanup-origin     exact captured admission-callback cleanup through the retained MutationPin owner
  interceptor-and-state-handler-callbacks   an authored EF interceptor callback, the state handler it subscribes or the drain it
                                            reaches, entered at the EF operation that raises it
  base-constructor-initializers             the `: base(...)` constructor of an authored FileStream subclass, at a
                                            member the table below lists, whose source declares the subclass
  in-memory-stream-base-constructor         the six reviewed Stream base constructor removals, pinned to exact base sources and
                                            absent from old-source parity; authored derived bodies still participate
  runtime-type-dispatch                     a call through an interface or abstract slot entering the implementation of the
                                            receiver's runtime type (the reviewed CredentialMirror set included)
  lease-receiver-proof                      an Effect withdrawn from a site whose Work is unchanged, and the group site whose
                                            receiver fails the proof
  stream-disposal-by-origin                 the Dispose of a stream that the member's own source declares as an in-memory or a
                                            database stream and no file-backed one, no longer the abstract Stream.Dispose

Invariants of a regeneration, checked whatever the labels are: no ProviderCall row is added without a Work and an Effect capsule
(a root NEW_ROOTS names is exempt from that only while the committed manifest does not hold it: the regeneration that commits it has
no rows to compare with, and every later regeneration holds it to the committed manifest like any other root),
the ProviderCall rows that have neither are the reviewed set (each under a root whose authority needs no Work, see
UNFRAMED_PROVIDER_CALL_ROOTS), and the Long Rest roots hold none; no ProviderCall row is removed unless its own file was edited,
an exact retirement proof or named rule explains it, or a ProviderCall row with both frames replaces it at the same site;
a root the committed manifest did not have
is a Long Rest root or one NEW_ROOTS names; every root of the committed manifest still has rows; the Long Rest roots admit the Long Rest kind and only
the handoff root reaches a provider; every Root Lease Formal row names a root that a Lease-Handoff binding row ties to its caller.

Exit status: 0 when no row is unexplained, 1 otherwise, 2 for an unreadable input.
"""

