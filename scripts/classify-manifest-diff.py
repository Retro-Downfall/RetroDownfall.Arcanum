def references_edited_source(manifest: Manifest, row: Row, edited: frozenset[str]) -> bool:
    return any(
        site.source_path in edited
        for reference in row.references
        for site in manifest.resolve(reference)
    )


def unresolved_references(manifest: Manifest, row: Row) -> list[str]:
    if manifest.version == 1:
        return [reference for reference in row.references if not manifest.resolve(reference)]

    def is_work_callee(callee: str) -> bool:
        return callee.endswith(".TryAcquireWorkLease") or callee == "RetroDownfall.Arcanum.Infrastructure.Data.IGrimoireWorkLease.RootLeaseFormal"

    def same_intrinsics(first: Row, candidate: Row, work: bool) -> bool:
        return candidate._replace(effect=first.effect, registered_root_work=first.registered_root_work,
            work=candidate.work if work else first.work) == first

    def same_work_context(first: Row, candidate: Row) -> bool:
        return candidate._replace(effect=first.effect) == first

    def drops_unrelated_effects(acquisitions: list[Row]) -> bool:
        root, work = row.registered_root_work, row.work
        effects = [candidate.effect for candidate in acquisitions]
        if root == "-" or work in ("-", root) or "-" in effects or len(set(effects)) != len(effects):
            return False
        for effect in effects:
            groups = [candidate for candidate in manifest.resolve(effect) if candidate.root == row.root
                      and candidate.kind == "EffectFrontier" and candidate.callee.endswith(".TryBeginExternalEffectGroup")]
            if len(groups) != 1:
                return False
            group = groups[0]
            if (group.effect != group.capsule_id or group.registered_root_work != root
                or group.admitted_work_kind != "-" or group.work in ("-", work)):
                return False
            physical_parents = [candidate for candidate in manifest.resolve(group.work) if candidate.root == row.root
                                and candidate.kind == "EffectFrontier" and is_work_callee(candidate.callee)]
            if physical_parents and not all(same_intrinsics(physical_parents[0], candidate, True) for candidate in physical_parents):
                return False
            parents = [candidate for candidate in physical_parents if candidate.registered_root_work == root]
            if len(parents) != 1 or parents[0].work != group.work or parents[0].admitted_work_kind == "-":
                return False
        return True

    def resolves(reference: str, kind: str) -> bool:
        physical = [candidate for candidate in manifest.resolve(reference) if candidate.root == row.root
            and candidate.kind == "EffectFrontier"
            and (is_work_callee(candidate.callee) if kind != "effect"
                else candidate.callee.endswith(".TryBeginExternalEffectGroup"))]
        work = kind != "effect"
        if physical and not all(same_intrinsics(physical[0], candidate, work) for candidate in physical):
            return False
        incoming_effect = kind == "effect" and row.kind == "EffectFrontier" and is_work_callee(row.callee)
        selected = physical
        if work:
            selected = [candidate for candidate in selected if candidate.work == reference]
            if kind == "registered-root-work":
                selected = [candidate for candidate in selected if candidate.registered_root_work == reference]
            elif row.registered_root_work != "-":
                selected = [candidate for candidate in selected if candidate.registered_root_work == row.registered_root_work]
        elif not incoming_effect and row.registered_root_work != "-":
            selected = [candidate for candidate in selected if candidate.registered_root_work == row.registered_root_work
                and (row.work == "-" or candidate.work == row.work)]
        if (kind == "effect" and not incoming_effect and row.work != "-" and row.registered_root_work == "-"
            and not (len(selected) == 1 and selected[0].work == row.work)):
            return False
        if len(selected) == 1:
            return True
        same_root = all(candidate.registered_root_work == row.registered_root_work for candidate in selected)
        work_self = (len(selected) > 1 and work and same_root and row.kind == "EffectFrontier"
            and is_work_callee(row.callee) and row.capsule_id == reference
            and (row.work if kind == "work" else row.registered_root_work) == reference
            and row.admitted_work_kind != "-" and selected.count(row) == 1
            and all(same_work_context(row, candidate) for candidate in selected))
        work_only = (len(selected) > 1 and work and same_root
            and row.kind in ("DatabaseAccess", "FileSystemRead", "OrdinaryConnectionRoute") and row.effect == "-"
            and selected[0].admitted_work_kind != "-"
            and all(same_work_context(selected[0], candidate) for candidate in selected)
            and (sum(candidate.effect == "-" for candidate in selected) == 1 or drops_unrelated_effects(selected)))
        return work_self or work_only

    unresolved = []
    for reference, kind in ((row.work, "work"), (row.registered_root_work, "registered-root-work"), (row.effect, "effect")):
        if reference != "-" and not resolves(reference, kind) and reference not in unresolved:
            unresolved.append(reference)
    return unresolved

def classify(
    committed: Manifest,
    regenerated: Manifest,
    edited: frozenset[str],
    parity: Manifest | None = None,
    sources: SourceTexts | None = None,
    baseline_observation: Manifest | None = None,
) -> list[Labelled]:
    if committed.version == 1 and regenerated.version == 2:
        # The absent v1 field is unknown, including where a v2 field is explicitly '-'.
        added = list(regenerated.counter.elements())
        removed = list(committed.counter.elements())
    else:
        added = list((regenerated.counter - committed.counter).elements())
        removed = list((committed.counter - regenerated.counter).elements())

    delta = [("+", row) for row in added] + [("-", row) for row in removed]

    # b-format: an added and a removed row are the same row once the lease marker is removed from every field. They are not
    # equal as they stand (the multiset difference already dropped equal rows), so the marker is the only difference between them.
    normalised_added = collections.Counter(row.normalised() for row in added)
    normalised_removed = collections.Counter(row.normalised() for row in removed)
    format_only = normalised_added & normalised_removed if committed.version == regenerated.version else collections.Counter()
    format_budget = {"+": collections.Counter(format_only), "-": collections.Counter(format_only)}

    partners_added: dict[tuple[str, ...], list[Row]] = collections.defaultdict(list)
    partners_removed: dict[tuple[str, ...], list[Row]] = collections.defaultdict(list)

    for row in added:
        partners_added[row.site].append(row)

    for row in removed:
        partners_removed[row.site].append(row)

    # A v1 unknown is paired only through one unambiguous exact v2 parity witness.
    # Counters preserve multiplicity and never merge distinct registered-root contexts.
    legacy_budget: dict[str, collections.Counter[Row]] = {"+": collections.Counter(), "-": collections.Counter()}
    legacy_details: dict[Row, str] = {}
    if committed.version == 1 and regenerated.version == 2 and parity is not None and parity.version == 2:
        old_by_legacy: dict[tuple[str, ...], list[Row]] = collections.defaultdict(list)
        parity_by_legacy: dict[tuple[str, ...], set[Row]] = collections.defaultdict(set)
        remaining_parity = parity.counter.copy()
        for row in removed:
            old_by_legacy[tuple(row[:13])].append(row)
        for row in parity.rows:
            parity_by_legacy[tuple(row[:13])].add(row)
        for row in added:
            key = tuple(row[:13])
            candidates = old_by_legacy[key]
            if (candidates and parity_by_legacy[key] == {row} and remaining_parity[row] > 0
                and not unresolved_references(parity, row) and not unresolved_references(regenerated, row)):
                old = candidates.pop()
                remaining_parity[row] -= 1
                legacy_budget["-"][old] += 1
                legacy_budget["+"][row] += 1
                witness = hashlib.sha256("\t".join(row).encode("utf-8")).hexdigest()
                detail = "v1 registered-root Work unknown; exact v2 parity row sha256 " + witness + "; registered-root Work " + row.registered_root_work
                legacy_details[old] = detail
                legacy_details[row] = detail

    labelled: list[Labelled] = []

    context = Context(committed, regenerated, parity, sources, baseline_observation)

    committed_roots = {row.root for row in committed.rows}

    reviewed_new_roots = reviewed_new_root_keys(regenerated)

    for side, row in delta:
        manifest = regenerated if side == "+" else committed
        other_manifest = committed if side == "+" else regenerated
        partners = (partners_removed if side == "+" else partners_added).get(row.site, [])

        stage = ""

        if parity is not None:
            in_parity = row in parity.counter
            if side == "-" and committed.version == 1 and regenerated.version == 2 and parity.version == 2:
                refinements = parity_by_legacy[tuple(row[:13])]
                if len(refinements) == 1:
                    witness = next(iter(refinements))
                    in_parity = remaining_parity[witness] > 0 and not unresolved_references(parity, witness)
                    if in_parity and legacy_budget[side][row] == 0:
                        remaining_parity[witness] -= 1

            # An added row is the checker's when the base source already yields it; a removed row is the checker's when the base
            # source no longer does.
            stage = "checker" if (in_parity if side == "+" else not in_parity) else "source"

        normal = row.normalised()

        if legacy_budget[side][row] > 0:
            legacy_budget[side][row] -= 1
            labelled.append(Labelled(side, row, "v1-provenance", stage=stage,
                detail=legacy_details[row]))
            continue

        if format_budget[side][normal] > 0:
            format_budget[side][normal] -= 1
            labelled.append(Labelled(side, row, "b-format", stage=stage))
            continue

        unresolved = unresolved_references(manifest, row)

        if unresolved:
            labelled.append(Labelled(side, row, "d", stage=stage, detail="unresolved frontier capsule " + unresolved[0][:12]))
            continue

        if (
            side == "+"
            and baseline_observation is not None
            and parity is not None
            and row not in committed.counter
            and row in baseline_observation.counter
            and row in parity.counter
        ):
            labelled.append(Labelled(side, row, "l", stage="baseline-ledger",
                detail="The exact baseline checker/source observation already discovers this complete row; the committed ledger omitted it."))
            continue

        # A row of a reviewed new root is the root's: the committed manifest has no row of it to compare with.
        if side == "+" and row.root not in committed_roots and selection_root(row) in reviewed_new_roots:
            labelled.append(Labelled(side, row, "n", stage=stage))
            continue

        own_edit = row.source_path in edited

        reference_edit = references_edited_source(manifest, row, edited) or any(
            references_edited_source(other_manifest, partner, edited) for partner in partners
        )

        if side == "-" and stage != "checker" and any(entry.covers(row, side) for entry in RETIRED_SOURCE_REACHES):
            reach, why = prove_reach(row, side, edited, sources, regenerated)
            if isinstance(reach, ExactSourceReach):
                labelled.append(Labelled(side, row, "r", rule=RETIRED_SOURCE_REACH_RULE, stage=stage, detail=why))
                continue

        if parity is None:
            if own_edit:
                labelled.append(Labelled(side, row, "a"))
            elif reference_edit:
                labelled.append(Labelled(side, row, "b"))
            else:
                labelled.append(rule_label(side, row, stage, context))

            continue

        if stage == "source":
            if own_edit:
                labelled.append(Labelled(side, row, "a", stage=stage))
            elif reference_edit:
                labelled.append(Labelled(side, row, "b", stage=stage))
            else:
                reach, why = prove_reach(row, side, edited, sources, regenerated)

                labelled.append(
                    Labelled(side, row, "r", stage=stage, detail=why)
                    if reach is not None
                    else Labelled(side, row, "d", stage=stage, detail=why)
                )
        else:
            labelled.append(rule_label(side, row, stage, context))

    return labelled


def rule_label(side: str, row: Row, stage: str, context: Context) -> Labelled:
    rules = matching_rules(row, side, context)

    if rules:
        return Labelled(side, row, "c", rule=rules[0].name, stage=stage, detail=",".join(rule.name for rule in rules[1:]))

    return Labelled(side, row, "d", stage=stage)


