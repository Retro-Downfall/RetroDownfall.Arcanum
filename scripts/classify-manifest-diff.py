HEADER = "# arcanum-hosted-producer-capsules v1"

COLUMNS = (
    "# root_type\tauthority_operation_id\tsource_path\tenclosing_type\tmember\tmember_identity\tkind\tcallee\t"
    "syntax_ordinal\tsyntax_sha256\twork_frontier_capsule_sha256\teffect_frontier_capsule_sha256\tadmitted_work_kind"
)

ROW_FIELDS = 13

# The marker an Effect id carries after the group it names, followed by the origin of the lease the group was begun on.
LEASE_MARKER = re.compile(r"@lease:.*$")


class Row(NamedTuple):
    root_type: str
    authority_operation_id: str
    source_path: str
    enclosing_type: str
    member: str
    member_identity: str
    kind: str
    callee: str
    syntax_ordinal: str
    syntax_sha256: str
    work: str
    effect: str
    admitted_work_kind: str

    @property
    def site(self) -> tuple[str, ...]:
        """The root and the site: everything but the frame."""
        return tuple(self[:10])

    @property
    def root(self) -> tuple[str, str]:
        return (self.root_type, self.authority_operation_id)

    @property
    def capsule_id(self) -> str:
        """HostedGrimoireProducerInventory.CapsuleId: SHA-256 over the site's own columns, upper-case hexadecimal."""
        evidence = "\n".join(
            (self.source_path, self.member_identity, self.kind, self.callee, self.syntax_ordinal, self.syntax_sha256)
        )

        return hashlib.sha256(evidence.encode("utf-8")).hexdigest().upper()

    @property
    def references(self) -> tuple[str, ...]:
        return tuple(value for value in (self.work, self.effect) if value != "-")

    def normalised(self) -> "Row":
        return Row(*(LEASE_MARKER.sub("", field) for field in self))


class Manifest:
    """A parsed manifest: its rows, and an index from capsule id to the rows of that site."""

    def __init__(self, rows: list[Row], name: str) -> None:
        self.name = name
        self.rows = rows
        self.counter = collections.Counter(rows)
        self.by_capsule: dict[str, list[Row]] = collections.defaultdict(list)
        self.by_site: dict[tuple[str, ...], list[Row]] = collections.defaultdict(list)

        for row in rows:
            self.by_capsule[row.capsule_id].append(row)
            self.by_site[row.site].append(row)

    def resolve(self, capsule_id: str) -> list[Row]:
        return self.by_capsule.get(capsule_id, [])


class ManifestError(Exception):
    pass


def parse_manifest(text: str, name: str) -> Manifest:
    lines = text.split("\n")

    if lines and lines[-1] == "":
        lines.pop()

    if len(lines) < 2 or lines[0] != HEADER:
        raise ManifestError(f"{name}: the first line must be exactly {HEADER!r}")

    if lines[1] != COLUMNS:
        raise ManifestError(f"{name}: the second line must be the exact v1 column header")

    rows: list[Row] = []

    for number, line in enumerate(lines[2:], start=3):
        fields = line.split("\t")

        if len(fields) != ROW_FIELDS:
            raise ManifestError(f"{name}:{number}: expected {ROW_FIELDS} tab-separated fields, found {len(fields)}")

        rows.append(Row(*fields))

    return Manifest(rows, name)


def read_manifest(path: str, name: str) -> Manifest:
    try:
        return parse_manifest(Path(path).read_text(encoding="utf-8"), name)
    except OSError as error:
        raise ManifestError(f"{name}: {error}") from error


# --- The source at the two revisions ---------------------------------------------------------------------------------------------
#
# Two things the classifier cannot read off a manifest row need the text of a source file: that an edit put a call on the chain that
# reaches a row (class r), and that the member a rule names declares what the rule says it does. Both read the file at the base
# and at the head, and a classifier run without a revision pair reads nothing, so it explains nothing of either kind.


class SourceTexts(Protocol):
    def base(self, path: str) -> str | None: ...

    def head(self, path: str) -> str | None: ...


class GitSourceTexts:
    """The text of a repository file at two revisions, or None where the file does not exist at one."""

    def __init__(self, repo: str, base: str, head: str) -> None:
        self.repo = repo
        self.revisions = {"base": base, "head": head}
        self.cache: dict[tuple[str, str], str | None] = {}

    def read(self, which: str, path: str) -> str | None:
        key = (which, path)

        if key not in self.cache:
            result = subprocess.run(
                ["git", "-C", self.repo, "show", f"{self.revisions[which]}:{path}"],
                check=False,
                capture_output=True,
                text=True,
            )

            self.cache[key] = result.stdout if result.returncode == 0 else None

        return self.cache[key]

    def base(self, path: str) -> str | None:
        return self.read("base", path)

    def head(self, path: str) -> str | None:
        return self.read("head", path)


def member_bodies(text: str, member: str) -> list[str]:
    """The text of every method, local function or constructor named `member` that has a body in a C# source.

    A textual reading and no more: a declaration is a line that opens with optional attributes and modifiers, then a type, then
    the name and a parameter list, and is followed by a block or an expression body. A call, an abstract declaration and an
    interface member have neither and are skipped. The caller asks only whether the text contains a declaration, so a body that
    is found twice (an overload) is a body that is searched twice.
    """
    declaration = re.compile(
        r"(?m)^[ \t]*(?:\[[^\]]*\]\s*)*(?:(?:public|private|internal|protected|static|async|unsafe|override|virtual|sealed|partial|extern|readonly|new)\s+)*"
        r"[\w<>\[\],.?()\s]*?\b" + re.escape(member) + r"\s*(?:<[^>\n]*>)?\s*\("
    )

    bodies: list[str] = []

    for match in declaration.finditer(text):
        position, depth = match.end(), 1

        while position < len(text) and depth:
            depth += {"(": 1, ")": -1}.get(text[position], 0)
            position += 1

        start = position

        while start < len(text) and text[start] not in "{;" and text[start : start + 2] != "=>":
            start += 1

        if start >= len(text) or text[start] == ";":
            continue

        if text.startswith("=>", start):
            end = text.find(";", start)

            bodies.append(text[match.start() : end + 1] if end >= 0 else text[match.start() :])

            continue

        depth, end = 0, start

        while end < len(text):
            depth += {"{": 1, "}": -1}.get(text[end], 0)

            if depth == 0:
                break

            end += 1

        bodies.append(text[match.start() : end + 1])

    return bodies


