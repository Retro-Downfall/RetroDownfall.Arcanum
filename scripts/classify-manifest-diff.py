@dataclasses.dataclass
class Labelled:
    side: str  # "+" added by the regeneration, "-" removed by it
    row: Row
    label: str
    rule: str = ""
    stage: str = ""
    detail: str = ""


def references_edited_source(manifest: Manifest, row: Row, edited: frozenset[str]) -> bool:
    return any(
        site.source_path in edited
        for reference in row.references
        for site in manifest.resolve(reference)
    )


def unresolved_references(manifest: Manifest, row: Row) -> list[str]:
    return [reference for reference in row.references if not manifest.resolve(reference)]


def classify(
    committed: Manifest,
    regenerated: Manifest,
    edited: frozenset[str],
    parity: Manifest | None = None,
    sources: SourceTexts | None = None,
) -> list[Labelled]:
    added = list((regenerated.counter - committed.counter).elements())
    removed = list((committed.counter - regenerated.counter).elements())

    delta = [("+", row) for row in added] + [("-", row) for row in removed]

    # b-format: an added and a removed row are the same row once the lease marker is removed from every field. They are not
    # equal as they stand (the multiset difference already dropped equal rows), so the marker is the only difference between them.
    normalised_added = collections.Counter(row.normalised() for row in added)
    normalised_removed = collections.Counter(row.normalised() for row in removed)
    format_only = normalised_added & normalised_removed
    format_budget = {"+": collections.Counter(format_only), "-": collections.Counter(format_only)}

    partners_added: dict[tuple[str, ...], list[Row]] = collections.defaultdict(list)
    partners_removed: dict[tuple[str, ...], list[Row]] = collections.defaultdict(list)

    for row in added:
        partners_added[row.site].append(row)

    for row in removed:
        partners_removed[row.site].append(row)

    labelled: list[Labelled] = []

    context = Context(committed, regenerated, parity, sources)

    committed_roots = {row.root for row in committed.rows}

    reviewed_new_roots = {(entry.root_type, entry.operation) for entry in NEW_ROOTS}

    for side, row in delta:
        manifest = regenerated if side == "+" else committed
        other_manifest = committed if side == "+" else regenerated
        partners = (partners_removed if side == "+" else partners_added).get(row.site, [])

        stage = ""

        if parity is not None:
            in_parity = row in parity.counter

            # An added row is the checker's when the base source already yields it; a removed row is the checker's when the base
            # source no longer does.
            stage = "checker" if (in_parity if side == "+" else not in_parity) else "source"

        normal = row.normalised()

        if format_budget[side][normal] > 0:
            format_budget[side][normal] -= 1
            labelled.append(Labelled(side, row, "b-format", stage=stage))
            continue

        unresolved = unresolved_references(manifest, row)

        if unresolved:
            labelled.append(Labelled(side, row, "d", stage=stage, detail="unresolved frontier capsule " + unresolved[0][:12]))
            continue

        # A row of a reviewed new root is the root's: the committed manifest has no row of it to compare with.
        if side == "+" and row.root not in committed_roots and selection_root(row) in reviewed_new_roots:
            labelled.append(Labelled(side, row, "n", stage=stage))
            continue

        own_edit = row.source_path in edited

        reference_edit = references_edited_source(manifest, row, edited) or any(
            references_edited_source(other_manifest, partner, edited) for partner in partners
        )

        if parity is None:
            if own_edit:
                labelled.append(Labelled(side, row, "a"))
            elif reference_edit:
                labelled.append(Labelled(side, row, "b"))
            else:
                labelled.append(rule_label(side, row, stage, context))

            continue

        if stage == "source":
            if own_edit:
                labelled.append(Labelled(side, row, "a", stage=stage))
            elif reference_edit:
                labelled.append(Labelled(side, row, "b", stage=stage))
            else:
                reach, why = prove_reach(row, side, edited, sources)

                labelled.append(
                    Labelled(side, row, "r", stage=stage, detail=why)
                    if reach is not None
                    else Labelled(side, row, "d", stage=stage, detail=why)
                )
        else:
            labelled.append(rule_label(side, row, stage, context))

    return labelled


def rule_label(side: str, row: Row, stage: str, context: Context) -> Labelled:
    rules = matching_rules(row, side, context)

    if rules:
        return Labelled(side, row, "c", rule=rules[0].name, stage=stage, detail=",".join(rule.name for rule in rules[1:]))

    return Labelled(side, row, "d", stage=stage)


