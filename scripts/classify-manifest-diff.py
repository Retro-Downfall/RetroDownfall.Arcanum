#!/usr/bin/env python3
"""The Diff Row Classifier for the reviewed hosted-producer capsule manifest.

The manifest (tests/RetroDownfall.Arcanum.Tests/Support/hosted-grimoire-producer-capsules-v1.tsv) is regenerated by the production
discovery with ARCANUM_UPDATE_HOSTED_PRODUCER_CAPSULES=1. A regeneration is reviewed, not trusted: every row it adds or removes
must be explained, and this script labels each one.

  python3 scripts/classify-manifest-diff.py --committed OLD.tsv --regenerated NEW.tsv --git-base b15d6960 [--git-head HEAD] [--repo .]
                            [--edited-sources FILE] [--parity PARITY.tsv] [--report OUT.tsv] [--json OUT.json]

Input
  --committed     the manifest before the regeneration
  --regenerated   the manifest after it
  --git-base/--git-head/--repo
                  the source files changed since the base (git diff --name-only BASE HEAD -- src); --edited-sources FILE
                  reads the same list from a file, one path per line
  --parity        optional. The manifest the same checker renders over the BASE source (the Old-Source Parity run: the
                  candidate checker with src/ swapped back to the base). With it, the cause of every delta row is known by
                  construction (see "Stages") instead of being inferred.

A row is one site seen from one root: (root_type, authority_operation_id) is the root, the next eight columns are the site, and
the last three are the site's frame (its Work capsule, its Effect capsule and the admitted work kind). A frame column holds the
capsule id of the acquisition or group site it names, and a capsule id is the SHA-256 of the site's own columns, so every
reference resolves inside the manifest that carries it. A row changed by the regeneration is a removed row and an added row that
share their site.

Classes (the first that applies; the order is the order below)
  b-format  the added and the removed row are equal once the "@lease:<origin>" marker an Effect id carries is normalised away
  a         the row's own site is in an edited source
  b         its Work or Effect capsule resolves to an acquisition, group or Root Lease Formal site in an edited source (in the
            manifest that carries the row, or in the one that carries the row it is paired with)
  r         (only with --parity) the site and its frames are all in unedited sources, and the source alone introduced or removed
            the row: the edit is on the call chain that reaches it
  c         introduced or removed by a named checker rule of this branch: the row matches the mechanical predicate of one rule in
            RULES below (with --parity, only a row that the checker alone introduced or removed is tested, and it is tested
            before any source class, so a row of an edited file that the checker yields over the unchanged base source is
            not credited to the edit)
  d         UNEXPLAINED. The review requires zero.

Stages (only with --parity). P is the manifest of the new checker over the base source, C the committed manifest and N the
regenerated one. P and C share a source, so a row in P and not in C is the checker's; N and P share a checker, so a row in N and
not in P is the source's. An added row is the checker's if it is in P and the source's if it is not; a removed row is the checker's
if it is not in P and the source's if it is. Without --parity the classes a, b and c are tried in that order on every row, so a
row that an edit and a rule could both explain is credited to the edit and a row only an edit on the call chain explains is d.

The rules (see RULES; each names the DESIGN paragraph that states its lane)
  interceptor-and-state-handler-callbacks   an authored EF interceptor callback, the state handler it subscribes or the drain it
                                            reaches, entered at the EF operation that raises it
  base-constructor-initializers             the `: base(...)` constructor of an authored FileStream or Stream subclass
  runtime-type-dispatch                     a call through an interface or abstract slot entering the implementation of the
                                            receiver's runtime type (the reviewed CredentialMirror set included)
  lease-receiver-proof                      an Effect withdrawn from a site whose Work is unchanged, and the group site whose
                                            receiver fails the proof
  stream-disposal-by-origin                 the Dispose of an in-memory or database stream, no longer the abstract Stream.Dispose

Invariants of a regeneration, checked whatever the labels are: no ProviderCall row is added without a Work and an Effect capsule
and the Long Rest roots hold none; a root the committed manifest did not have is a Long Rest root; every root of the committed
manifest still has rows; the Long Rest roots admit the Long Rest kind and only the handoff root reaches a provider; every Root
Lease Formal row names a root that a Lease-Handoff binding row ties to its caller.

Exit status: 0 when no row is unexplained, 1 otherwise, 2 for an unreadable input.
"""

from __future__ import annotations

import argparse
import collections
import dataclasses
import hashlib
import json
import re
import subprocess
import sys
from pathlib import Path
from typing import Callable, Iterable, NamedTuple

HEADER = "# arcanum-hosted-producer-capsules v1"

COLUMNS = (
    "# root_type\tauthority_operation_id\tsource_path\tenclosing_type\tmember\tmember_identity\tkind\tcallee\t"
    "syntax_ordinal\tsyntax_sha256\twork_frontier_capsule_sha256\teffect_frontier_capsule_sha256\tadmitted_work_kind"
)

ROW_FIELDS = 13

# The marker an Effect id carries after the group it names, followed by the origin of the lease the group was begun on.
LEASE_MARKER = re.compile(r"@lease:.*$")


class Row(NamedTuple):
    root_type: str
    authority_operation_id: str
    source_path: str
    enclosing_type: str
    member: str
    member_identity: str
    kind: str
    callee: str
    syntax_ordinal: str
    syntax_sha256: str
    work: str
    effect: str
    admitted_work_kind: str

    @property
    def site(self) -> tuple[str, ...]:
        """The root and the site: everything but the frame."""
        return tuple(self[:10])

    @property
    def root(self) -> tuple[str, str]:
        return (self.root_type, self.authority_operation_id)

    @property
    def capsule_id(self) -> str:
        """HostedGrimoireProducerInventory.CapsuleId: SHA-256 over the site's own columns, upper-case hexadecimal."""
        evidence = "\n".join(
            (self.source_path, self.member_identity, self.kind, self.callee, self.syntax_ordinal, self.syntax_sha256)
        )

        return hashlib.sha256(evidence.encode("utf-8")).hexdigest().upper()

    @property
    def references(self) -> tuple[str, ...]:
        return tuple(value for value in (self.work, self.effect) if value != "-")

    def normalised(self) -> "Row":
        return Row(*(LEASE_MARKER.sub("", field) for field in self))


class Manifest:
    """A parsed manifest: its rows, and an index from capsule id to the rows of that site."""

    def __init__(self, rows: list[Row], name: str) -> None:
        self.name = name
        self.rows = rows
        self.counter = collections.Counter(rows)
        self.by_capsule: dict[str, list[Row]] = collections.defaultdict(list)
        self.by_site: dict[tuple[str, ...], list[Row]] = collections.defaultdict(list)

        for row in rows:
            self.by_capsule[row.capsule_id].append(row)
            self.by_site[row.site].append(row)

    def resolve(self, capsule_id: str) -> list[Row]:
        return self.by_capsule.get(capsule_id, [])


class ManifestError(Exception):
    pass


def parse_manifest(text: str, name: str) -> Manifest:
    lines = text.split("\n")

    if lines and lines[-1] == "":
        lines.pop()

    if len(lines) < 2 or lines[0] != HEADER:
        raise ManifestError(f"{name}: the first line must be exactly {HEADER!r}")

    if lines[1] != COLUMNS:
        raise ManifestError(f"{name}: the second line must be the exact v1 column header")

    rows: list[Row] = []

    for number, line in enumerate(lines[2:], start=3):
        fields = line.split("\t")

        if len(fields) != ROW_FIELDS:
            raise ManifestError(f"{name}:{number}: expected {ROW_FIELDS} tab-separated fields, found {len(fields)}")

        rows.append(Row(*fields))

    return Manifest(rows, name)


def read_manifest(path: str, name: str) -> Manifest:
    try:
        return parse_manifest(Path(path).read_text(encoding="utf-8"), name)
    except OSError as error:
        raise ManifestError(f"{name}: {error}") from error


# --- The named checker rules of this branch -------------------------------------------------------------------------------------
#
# A rule is a footprint: what one lane of the checker makes the discovery see, or stop seeing, over the unchanged base source. Its
# predicate reads the row (and, for a row whose frame the rule changes, the same site in the manifest it is compared with), never
# the rest of the diff. Each rule names the paragraph of docs/Arcanum.DESIGN.md that states the lane. A rule is added here only
# with the mechanism that makes it explain the rows it matches (the Old-Source Parity traversal compared with the delivery
# traversal shows it: the first call edge that is new, and the tag of it); a row that no rule matches stays unexplained.

COVENANT_DATA = "RetroDownfall.Arcanum.Infrastructure.Data.Covenant."

SECURITY = "RetroDownfall.Arcanum.Infrastructure.Security."

# The callback types of the one enrolment interceptor the Covenant installs on every context, the state handler it subscribes
# and the pool drain they reach. Every state of them in the delivery traversal is entered through an `interceptor@` or a
# `statechange@` edge, which the traversal before the lane did not have.
INTERCEPTOR_CALLBACK_TYPES = frozenset(
    COVENANT_DATA + name
    for name in ("CovenantConnectionEnrolmentInterceptor", "CovenantSqliteConnectionInitializer", "CovenantConnectionDrain")
)

# Types whose members a call through a slot reaches only when the slot is resolved on the receiver's runtime type: the
# OS-credential and Data Protection stores behind `ISecretStore` and the `CredentialMirror` Reviewed Closed Override Set (the
# owner-only file primitives they write through), and the Saga store and entry queries behind two container-resolved
# interfaces. Before the lane the traversal ended at the interface member, which declares no body.
SLOT_DISPATCH_TYPES = frozenset(
    SECURITY + name
    for name in (
        "FileHandleIdentityInterop",
        "MirroredOsCredential",
        "OwnerOnlyAtomicFile",
        "ProtectedCredentialFile",
        "SecureFilePermissions",
        "SecureFileReader",
    )
) | frozenset(
    (
        "RetroDownfall.Arcanum.Infrastructure.Data.GrimoireSqlCommandFactory",
        "RetroDownfall.Arcanum.Infrastructure.Data.SagaMemoryStore",
        "RetroDownfall.Arcanum.Infrastructure.Repositories.EntryTemporalQueries",
    )
)

# The base constructor an authored FileStream or Stream subclass runs from its `: base(...)` initializer. No operation of the
# constructor body binds it, so it is a site only because the census lists it.
BASE_CONSTRUCTOR_CALLEES = frozenset(("System.IO.FileStream..ctor", "System.IO.Stream..ctor"))

STREAM_DISPOSE = "System.IO.Stream.Dispose"

GROUP_CALLEE_SUFFIX = ".TryBeginExternalEffectGroup"


class Context:
    """The manifests a rule may compare a row with."""

    def __init__(self, committed: Manifest, regenerated: Manifest, parity: Manifest | None) -> None:
        self.committed = committed
        self.regenerated = regenerated
        self.parity = parity

    @staticmethod
    def same_site(manifest: Manifest | None, row: Row) -> list[Row]:
        return manifest.by_site.get(row.site, []) if manifest is not None else []


@dataclasses.dataclass(frozen=True)
class Rule:
    name: str
    lane: str
    side: str  # "+" explains an added row, "-" a removed one, "+-" either
    summary: str
    predicate: Callable[[Row, str, Context], bool]

    def matches(self, row: Row, side: str, context: Context) -> bool:
        return side in self.side and self.predicate(row, side, context)


def is_interceptor_callback(row: Row, side: str, context: Context) -> bool:
    return row.enclosing_type in INTERCEPTOR_CALLBACK_TYPES


def is_slot_dispatch(row: Row, side: str, context: Context) -> bool:
    return row.enclosing_type in SLOT_DISPATCH_TYPES


def is_base_constructor(row: Row, side: str, context: Context) -> bool:
    return row.kind in ("FileSystemEffect", "FileSystemRead") and row.callee in BASE_CONSTRUCTOR_CALLEES


def withdraws_effect(row: Row, side: str, context: Context) -> bool:
    """The checker keeps the site and its Work and takes the Effect away, or drops the group site whose Effect it would grant."""
    if side == "-":
        partners = context.same_site(context.parity, row)

        if row.kind == "EffectFrontier" and row.callee.endswith(GROUP_CALLEE_SUFFIX) and context.parity is not None and not partners:
            return True

        return row.effect != "-" and any(partner.work == row.work and partner.effect == "-" for partner in partners)

    return row.effect == "-" and any(
        partner.work == row.work and partner.effect != "-" for partner in context.same_site(context.committed, row)
    )


def is_stream_disposal_by_origin(row: Row, side: str, context: Context) -> bool:
    """The disposal of a stream the checker now resolves to the exact in-memory or database stream it came from."""
    return (
        row.kind == "FileSystemEffect"
        and row.callee == STREAM_DISPOSE
        and context.parity is not None
        and not context.same_site(context.parity, row)
    )


RULES: tuple[Rule, ...] = (
    Rule(
        "interceptor-and-state-handler-callbacks",
        "Interceptor and Logger Lane; Connection State Handlers; Effect on the Shipped Graph",
        "+",
        "the authored EF interceptor callbacks, the state handler they subscribe and the drain they reach are entered at the EF "
        "operations that raise them",
        is_interceptor_callback,
    ),
    Rule(
        "base-constructor-initializers",
        "Implicit Call Census (constructor initializers)",
        "+",
        "the `: base(...)` constructor of an authored FileStream or Stream subclass is a site the census lists",
        is_base_constructor,
    ),
    Rule(
        "runtime-type-dispatch",
        "Implicit Call Census: Accessors and virtual methods the runtime type selects; Reviewed Closed Override Sets",
        "+",
        "a call through an interface or abstract slot enters the authored implementation of the receiver's runtime type "
        "(the reviewed CredentialMirror set included) instead of ending at the bodiless slot",
        is_slot_dispatch,
    ),
    Rule(
        "lease-receiver-proof",
        "Lease Receiver Proof (CK-3); Admission origins follow handles, not data",
        "+-",
        "an Effect is granted only to a group whose receiver is a must-alias of the Work's lease origin, so the Effect of a site "
        "whose group fails the proof is withdrawn and the group itself is no frontier",
        withdraws_effect,
    ),
    Rule(
        "stream-disposal-by-origin",
        "Implicit Call Census (using disposals); EF and ADO.NET semantics",
        "-",
        "the Dispose of an in-memory or database stream is no filesystem effect; the abstract Stream.Dispose the checker "
        "assumed before is gone",
        is_stream_disposal_by_origin,
    ),
)


def matching_rules(row: Row, side: str, context: Context) -> list[Rule]:
    return [rule for rule in RULES if rule.matches(row, side, context)]


# --- Classification -------------------------------------------------------------------------------------------------------------

CLASS_ORDER = ("b-format", "a", "b", "r", "c", "d")

CLASS_TITLES = {
    "b-format": "the Effect id differs only by its @lease: marker",
    "a": "own site in an edited source",
    "b": "Work or Effect capsule names an edited acquisition, group or formal site",
    "r": "unedited site and frames reached through an edited call chain (parity)",
    "c": "introduced or removed by a named checker rule",
    "d": "UNEXPLAINED",
}


@dataclasses.dataclass
class Labelled:
    side: str  # "+" added by the regeneration, "-" removed by it
    row: Row
    label: str
    rule: str = ""
    stage: str = ""
    detail: str = ""


def references_edited_source(manifest: Manifest, row: Row, edited: frozenset[str]) -> bool:
    return any(
        site.source_path in edited
        for reference in row.references
        for site in manifest.resolve(reference)
    )


def unresolved_references(manifest: Manifest, row: Row) -> list[str]:
    return [reference for reference in row.references if not manifest.resolve(reference)]


def classify(
    committed: Manifest,
    regenerated: Manifest,
    edited: frozenset[str],
    parity: Manifest | None = None,
) -> list[Labelled]:
    added = list((regenerated.counter - committed.counter).elements())
    removed = list((committed.counter - regenerated.counter).elements())

    delta = [("+", row) for row in added] + [("-", row) for row in removed]

    # b-format: an added and a removed row are the same row once the lease marker is removed from every field. They are not
    # equal as they stand (the multiset difference already dropped equal rows), so the marker is the only difference between them.
    normalised_added = collections.Counter(row.normalised() for row in added)
    normalised_removed = collections.Counter(row.normalised() for row in removed)
    format_only = normalised_added & normalised_removed
    format_budget = {"+": collections.Counter(format_only), "-": collections.Counter(format_only)}

    partners_added: dict[tuple[str, ...], list[Row]] = collections.defaultdict(list)
    partners_removed: dict[tuple[str, ...], list[Row]] = collections.defaultdict(list)

    for row in added:
        partners_added[row.site].append(row)

    for row in removed:
        partners_removed[row.site].append(row)

    labelled: list[Labelled] = []

    context = Context(committed, regenerated, parity)

    for side, row in delta:
        manifest = regenerated if side == "+" else committed
        other_manifest = committed if side == "+" else regenerated
        partners = (partners_removed if side == "+" else partners_added).get(row.site, [])

        stage = ""

        if parity is not None:
            in_parity = row in parity.counter

            # An added row is the checker's when the base source already yields it; a removed row is the checker's when the base
            # source no longer does.
            stage = "checker" if (in_parity if side == "+" else not in_parity) else "source"

        normal = row.normalised()

        if format_budget[side][normal] > 0:
            format_budget[side][normal] -= 1
            labelled.append(Labelled(side, row, "b-format", stage=stage))
            continue

        unresolved = unresolved_references(manifest, row)

        if unresolved:
            labelled.append(Labelled(side, row, "d", stage=stage, detail="unresolved frontier capsule " + unresolved[0][:12]))
            continue

        own_edit = row.source_path in edited

        reference_edit = references_edited_source(manifest, row, edited) or any(
            references_edited_source(other_manifest, partner, edited) for partner in partners
        )

        if parity is None:
            if own_edit:
                labelled.append(Labelled(side, row, "a"))
            elif reference_edit:
                labelled.append(Labelled(side, row, "b"))
            else:
                labelled.append(rule_label(side, row, stage, context))

            continue

        if stage == "source":
            if own_edit:
                labelled.append(Labelled(side, row, "a", stage=stage))
            elif reference_edit:
                labelled.append(Labelled(side, row, "b", stage=stage))
            else:
                labelled.append(Labelled(side, row, "r", stage=stage))
        else:
            labelled.append(rule_label(side, row, stage, context))

    return labelled


def rule_label(side: str, row: Row, stage: str, context: Context) -> Labelled:
    rules = matching_rules(row, side, context)

    if rules:
        return Labelled(side, row, "c", rule=rules[0].name, stage=stage, detail=",".join(rule.name for rule in rules[1:]))

    return Labelled(side, row, "d", stage=stage)


# --- Invariants of a regenerated manifest the review requires ---------------------------------------------------------------


@dataclasses.dataclass
class Invariant:
    name: str
    description: str
    violations: list[str]


def is_long_rest_root(root: tuple[str, str]) -> bool:
    return "LongRest" in root[0] or "LongRest" in root[1]


def check_invariants(committed: Manifest, regenerated: Manifest) -> list[Invariant]:
    """The facts about a regeneration that hold whatever its rows are labelled."""

    def unframed(manifest: Manifest) -> set[Row]:
        return {row for row in manifest.rows if row.kind == "ProviderCall" and "-" in (row.work, row.effect)}

    # A lifecycle or recovery root (StartAsync, StopAsync, a startup pass) is judged without a Work frontier by design, so
    # the committed manifest already holds unframed ProviderCall rows. The regeneration must not add one, and the Long Rest
    # roots, which are ordinary hosted work, must hold none.
    added_unframed = sorted(unframed(regenerated) - unframed(committed))

    long_rest_unframed = [row for row in unframed(regenerated) if is_long_rest_root(row.root)]

    old_roots = {row.root for row in committed.rows}
    new_roots = {row.root for row in regenerated.rows}

    foreign_new_roots = sorted(root for root in new_roots - old_roots if not is_long_rest_root(root))

    lost_roots = sorted(old_roots - new_roots)

    formals = [row for row in regenerated.rows if row.kind == "EffectFrontier" and row.callee.endswith(".IGrimoireWorkLease.RootLeaseFormal")]

    bound_roots = {row.callee for row in regenerated.rows if row.kind == "LeaseHandoff"}

    unbound = sorted({row.root for row in formals if row.authority_operation_id not in bound_roots})

    # The Long Rest worker admits its kind where it acquires or is handed the lease, and only the root it hands the lease to
    # (the one with a Root Lease Formal row) reaches the provider.
    handoff_roots = {row.root for row in formals if is_long_rest_root(row.root)}

    long_rest_structure = [
        f"{row.root_type}|{row.authority_operation_id}|{row.callee}: admitted kind {row.admitted_work_kind}"
        for row in regenerated.rows
        if is_long_rest_root(row.root)
        and row.kind == "EffectFrontier"
        and (row.callee.endswith(".TryAcquireWorkLease") or row.callee.endswith(".IGrimoireWorkLease.RootLeaseFormal"))
        and row.admitted_work_kind != "LongRestSweep"
    ] + [
        f"{row.root_type}|{row.authority_operation_id}|{row.callee}: a provider call outside the handoff root"
        for row in regenerated.rows
        if is_long_rest_root(row.root) and row.kind == "ProviderCall" and row.root not in handoff_roots
    ]

    return [
        Invariant(
            "provider-call-frames",
            "the regeneration adds no ProviderCall row without a Work and an Effect capsule, and the Long Rest roots hold none",
            [f"{row.root_type}|{row.authority_operation_id}|{row.callee}|{row.member}" for row in added_unframed]
            + [f"{row.root_type}|{row.authority_operation_id}|{row.callee}|{row.member}" for row in long_rest_unframed],
        ),
        Invariant(
            "new-roots",
            "a root the committed manifest did not have is a Long Rest root",
            [f"{root[0]}|{root[1]}" for root in foreign_new_roots],
        ),
        Invariant(
            "kept-roots",
            "every root of the committed manifest still has rows",
            [f"{root[0]}|{root[1]}" for root in lost_roots],
        ),
        Invariant(
            "long-rest-structure",
            "the Long Rest roots admit the Long Rest kind and only the handoff root reaches a provider",
            long_rest_structure,
        ),
        Invariant(
            "handoff-binding",
            "every Root Lease Formal row names a root that a Lease-Handoff binding row ties to its caller",
            [f"{root[0]}|{root[1]}" for root in unbound],
        ),
    ]


# --- Reporting ------------------------------------------------------------------------------------------------------------------


def edited_sources_from_git(repo: str, base: str, head: str) -> frozenset[str]:
    result = subprocess.run(
        ["git", "-C", repo, "diff", "--name-only", base, head, "--", "src"],
        check=False,
        capture_output=True,
        text=True,
    )

    if result.returncode != 0:
        raise ManifestError("git diff failed: " + result.stderr.strip())

    return frozenset(line for line in result.stdout.split("\n") if line)


def summarise(labelled: list[Labelled]) -> dict[str, object]:
    by_class = collections.Counter(item.label for item in labelled)
    by_rule = collections.Counter(item.rule for item in labelled if item.label == "c")
    by_stage = collections.Counter((item.stage, item.label) for item in labelled if item.stage)
    by_side = collections.Counter((item.side, item.label) for item in labelled)

    return {
        "classes": {name: by_class.get(name, 0) for name in CLASS_ORDER},
        "rules": dict(sorted(by_rule.items())),
        "stages": {f"{stage}:{label}": count for (stage, label), count in sorted(by_stage.items())},
        "sides": {f"{side}:{label}": count for (side, label), count in sorted(by_side.items())},
        "added": sum(1 for item in labelled if item.side == "+"),
        "removed": sum(1 for item in labelled if item.side == "-"),
        "unexplained": by_class.get("d", 0),
    }


def render_summary(
    summary: dict[str, object],
    committed: Manifest,
    regenerated: Manifest,
    edited: frozenset[str],
    invariants: list[Invariant],
    parity: Manifest | None,
) -> str:
    lines = [
        "Diff Row Classifier",
        f"committed rows: {len(committed.rows)}",
        f"regenerated rows: {len(regenerated.rows)}",
        f"added rows: {summary['added']}",
        f"removed rows: {summary['removed']}",
        f"edited sources: {len(edited)}",
        f"parity rows: {len(parity.rows) if parity is not None else 'not given'}",
        "",
        "class counts",
    ]

    classes = summary["classes"]

    assert isinstance(classes, dict)

    for name in CLASS_ORDER:
        lines.append(f"  {name:<9}{classes[name]:>6}  {CLASS_TITLES[name]}")

    rules = summary["rules"]

    assert isinstance(rules, dict)

    if rules:
        lines += ["", "class c by rule"]
        lines += [f"  {name:<44}{count:>6}" for name, count in rules.items()]

    stages = summary["stages"]

    assert isinstance(stages, dict)

    if stages:
        lines += ["", "stage and class"]
        lines += [f"  {name:<20}{count:>6}" for name, count in stages.items()]

    lines += ["", "side and class"]
    sides = summary["sides"]

    assert isinstance(sides, dict)

    lines += [f"  {name:<20}{count:>6}" for name, count in sides.items()]

    lines += ["", "invariants"]

    for invariant in invariants:
        verdict = "ok" if not invariant.violations else f"VIOLATED ({len(invariant.violations)})"

        lines.append(f"  {invariant.name:<22}{verdict}  {invariant.description}")

        lines += [f"    {violation}" for violation in invariant.violations[:10]]

    lines += ["", f"unexplained rows: {summary['unexplained']}"]

    return "\n".join(lines) + "\n"


def write_report(path: str, labelled: list[Labelled]) -> None:
    order = {name: index for index, name in enumerate(CLASS_ORDER)}

    ranked = sorted(labelled, key=lambda item: (order[item.label], item.rule, item.side, item.row))

    with open(path, "w", encoding="utf-8", newline="") as handle:
        handle.write("class\trule\tstage\tside\tdetail\t" + COLUMNS[2:] + "\n")

        for item in ranked:
            handle.write("\t".join((item.label, item.rule, item.stage, item.side, item.detail, *item.row)) + "\n")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Label every row a manifest regeneration adds or removes.")
    parser.add_argument("--committed", required=True)
    parser.add_argument("--regenerated", required=True)
    parser.add_argument("--edited-sources", help="file with the changed source paths, one per line")
    parser.add_argument("--git-base", help="revision the manifest was last regenerated for")
    parser.add_argument("--git-head", default="HEAD")
    parser.add_argument("--repo", default=".")
    parser.add_argument("--parity", help="manifest of the same checker over the base source")
    parser.add_argument("--report", help="write every labelled row to this TSV")
    parser.add_argument("--json", dest="json_path", help="write the summary to this JSON file")
    arguments = parser.parse_args(argv)

    try:
        committed = read_manifest(arguments.committed, "committed")
        regenerated = read_manifest(arguments.regenerated, "regenerated")
        parity = read_manifest(arguments.parity, "parity") if arguments.parity else None

        if arguments.edited_sources:
            edited = frozenset(
                line.strip()
                for line in Path(arguments.edited_sources).read_text(encoding="utf-8").split("\n")
                if line.strip()
            )
        elif arguments.git_base:
            edited = edited_sources_from_git(arguments.repo, arguments.git_base, arguments.git_head)
        else:
            parser.error("give --edited-sources or --git-base")
    except (ManifestError, OSError) as error:
        print(f"classify-manifest-diff: {error}", file=sys.stderr)

        return 2

    labelled = classify(committed, regenerated, edited, parity)
    summary = summarise(labelled)
    invariants = check_invariants(committed, regenerated)

    sys.stdout.write(render_summary(summary, committed, regenerated, edited, invariants, parity))

    if arguments.report:
        write_report(arguments.report, labelled)

    if arguments.json_path:
        Path(arguments.json_path).write_text(json.dumps(summary, indent=2, sort_keys=True) + "\n", encoding="utf-8")

    return 1 if summary["unexplained"] or any(invariant.violations for invariant in invariants) else 0


if __name__ == "__main__":
    sys.exit(main())
