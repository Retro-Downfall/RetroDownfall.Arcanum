CREATE TABLE IF NOT EXISTS guild_signets (
    SignetId TEXT NOT NULL PRIMARY KEY,
    AgentId TEXT NOT NULL,
    RunId TEXT NOT NULL UNIQUE,
    CommissionId TEXT NOT NULL UNIQUE,
    RootCommissionId TEXT NOT NULL,
    IssuerSignetId TEXT NULL REFERENCES guild_signets(SignetId) DEFERRABLE INITIALLY DEFERRED,
    GrantJson TEXT NOT NULL,
    IssuedAtUtc TEXT NOT NULL,
    OriginPrincipalId TEXT NOT NULL,
    SessionId TEXT NULL,
    CampaignId TEXT NULL,
    WorkspaceId TEXT NULL,
    WorkspaceIdentityPolicyVersion INTEGER NULL,
    WorkspaceIdentityRevision INTEGER NULL,
    WorkspaceRootIdentity BLOB NULL,
    PeerId TEXT NULL,
    PeerGrantRevision TEXT NULL,
    InstallationGeneration TEXT NOT NULL,
    AuthorityEpoch TEXT NOT NULL,
    Revision INTEGER NOT NULL CHECK(typeof(Revision)='integer' AND Revision>=1),
    CredentialGeneration INTEGER NOT NULL CHECK(typeof(CredentialGeneration)='integer' AND CredentialGeneration>=1),
    TokenDigest BLOB NOT NULL CHECK(typeof(TokenDigest)='blob' AND length(TokenDigest)=32),
    RevocationGeneration INTEGER NOT NULL CHECK(typeof(RevocationGeneration)='integer' AND RevocationGeneration>=0),
    Revoked INTEGER NOT NULL CHECK(Revoked IN(0,1)),
    RestoredInert INTEGER NOT NULL CHECK(RestoredInert IN(0,1)),
    Retired INTEGER NOT NULL CHECK(Retired IN(0,1)),
    CancellationRequested INTEGER NOT NULL DEFAULT 0 CHECK(CancellationRequested IN(0,1)),
    CHECK((CommissionId=RootCommissionId AND IssuerSignetId IS NULL) OR (CommissionId<>RootCommissionId AND IssuerSignetId IS NOT NULL)),
    CHECK((PeerId IS NULL)=(PeerGrantRevision IS NULL)),
    CHECK((WorkspaceId IS NULL AND WorkspaceIdentityPolicyVersion IS NULL AND WorkspaceIdentityRevision IS NULL AND WorkspaceRootIdentity IS NULL)
       OR (WorkspaceId IS NOT NULL AND WorkspaceIdentityPolicyVersion IS NOT NULL AND WorkspaceIdentityRevision IS NOT NULL
           AND WorkspaceIdentityPolicyVersion>=1 AND WorkspaceIdentityRevision>=1 AND typeof(WorkspaceRootIdentity)='blob' AND length(WorkspaceRootIdentity)=32))
);
