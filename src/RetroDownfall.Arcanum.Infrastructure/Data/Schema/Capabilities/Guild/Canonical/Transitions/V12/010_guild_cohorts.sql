CREATE TABLE IF NOT EXISTS guild_cohorts (
    Id TEXT NOT NULL PRIMARY KEY,
    RootQuestId TEXT NOT NULL REFERENCES guild_quests(Id) ON DELETE RESTRICT,
    IssuerQuestId TEXT NOT NULL REFERENCES guild_quests(Id) ON DELETE RESTRICT,
    CampaignId TEXT NULL,
    Name TEXT NULL CHECK(Name IS NULL OR length(CAST(Name AS BLOB)) BETWEEN 1 AND 65536),
    PolicyCode INTEGER NOT NULL CHECK(PolicyCode IN (1,2,3)),
    Quorum INTEGER NULL CHECK((PolicyCode=3 AND Quorum>=1) OR (PolicyCode<>3 AND Quorum IS NULL)),
    MimeType TEXT NOT NULL CHECK(MimeType IN ('text/plain','application/json')),
    GrantJson TEXT NOT NULL CHECK(length(CAST(GrantJson AS BLOB)) BETWEEN 1 AND 65536),
    AllocationAccountId TEXT NOT NULL UNIQUE REFERENCES guild_budget_accounts(AccountId) ON DELETE RESTRICT,
    StateCode INTEGER NOT NULL CHECK(StateCode BETWEEN 1 AND 6),
    Revision INTEGER NOT NULL CHECK(Revision>=1),
    MembershipVersion INTEGER NOT NULL CHECK(MembershipVersion>=0),
    ActiveMemberCount INTEGER NOT NULL DEFAULT 0 CHECK(ActiveMemberCount>=0),
    FrozenMemberCount INTEGER NULL CHECK(FrozenMemberCount IS NULL OR FrozenMemberCount>=1),
    ClosedMembershipVersion INTEGER NULL CHECK(ClosedMembershipVersion IS NULL OR ClosedMembershipVersion BETWEEN 1 AND MembershipVersion),
    ResultSequence INTEGER NOT NULL DEFAULT 0 CHECK(ResultSequence>=0),
    DecisionCode INTEGER NULL CHECK(DecisionCode IS NULL OR DecisionCode BETWEEN 1 AND 3),
    ReasonCode TEXT NULL,
    EventWatermark INTEGER NOT NULL DEFAULT 0 CHECK(EventWatermark>=0),
    Retired INTEGER NOT NULL DEFAULT 0 CHECK(typeof(Retired)='integer' AND Retired IN(0,1)),
    CHECK((Retired=0 AND Name IS NOT NULL) OR (Retired=1 AND Name IS NULL)),
    CHECK((StateCode=1 AND ClosedMembershipVersion IS NULL) OR StateCode<>1)
);
