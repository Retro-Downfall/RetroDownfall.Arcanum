CREATE TABLE IF NOT EXISTS long_rest_provider_effects (
    WorkItemId TEXT NOT NULL PRIMARY KEY REFERENCES long_rest_work_items(WorkItemId) ON DELETE CASCADE,
    WorkDigest BLOB NOT NULL CHECK (length(WorkDigest) = 32),
    OriginalWorkJson TEXT NOT NULL CHECK (typeof(OriginalWorkJson) = 'text' AND length(CAST(OriginalWorkJson AS BLOB)) BETWEEN 2 AND 14336 AND json_valid(OriginalWorkJson)),
    AttemptId TEXT NOT NULL UNIQUE,
    PayloadKindCode INTEGER NOT NULL CHECK (PayloadKindCode BETWEEN 1 AND 3),
    PhysicalOrdinal INTEGER NOT NULL CHECK (typeof(PhysicalOrdinal) = 'integer' AND PhysicalOrdinal > 0),
    Revision INTEGER NOT NULL CHECK (typeof(Revision) = 'integer' AND Revision >= 0),
    StateCode INTEGER NOT NULL CHECK (StateCode BETWEEN 1 AND 6),
    PayloadDigest BLOB NOT NULL CHECK (length(PayloadDigest) = 32),
    DestinationDigest BLOB NOT NULL CHECK (length(DestinationDigest) = 32),
    DisclosureReceiptDigest BLOB NULL CHECK (DisclosureReceiptDigest IS NULL OR length(DisclosureReceiptDigest) = 32),
    SentCount INTEGER NOT NULL DEFAULT 0 CHECK (typeof(SentCount) = 'integer' AND SentCount >= 0),
    PaidCount INTEGER NOT NULL DEFAULT 0 CHECK (typeof(PaidCount) = 'integer' AND PaidCount >= 0),
    InvalidCount INTEGER NOT NULL DEFAULT 0 CHECK (typeof(InvalidCount) = 'integer' AND InvalidCount >= 0),
    FailureCount INTEGER NOT NULL DEFAULT 0 CHECK (typeof(FailureCount) = 'integer' AND FailureCount >= 0),
    InputTokens INTEGER NOT NULL DEFAULT 0 CHECK (typeof(InputTokens) = 'integer' AND InputTokens >= 0),
    OutputTokens INTEGER NOT NULL DEFAULT 0 CHECK (typeof(OutputTokens) = 'integer' AND OutputTokens >= 0),
    TotalTokens INTEGER NOT NULL DEFAULT 0 CHECK (typeof(TotalTokens) = 'integer' AND TotalTokens >= 0),
    CachedInputTokens INTEGER NOT NULL DEFAULT 0 CHECK (typeof(CachedInputTokens) = 'integer' AND CachedInputTokens >= 0),
    ReasoningTokens INTEGER NOT NULL DEFAULT 0 CHECK (typeof(ReasoningTokens) = 'integer' AND ReasoningTokens >= 0),
    CostUsd TEXT NULL CHECK (CostUsd IS NULL OR typeof(CostUsd) = 'text'),
    CompletionJson TEXT NULL CHECK (CompletionJson IS NULL OR length(CAST(CompletionJson AS BLOB)) BETWEEN 2 AND 4096),
    FailureCode TEXT NULL CHECK (FailureCode IS NULL OR length(FailureCode) BETWEEN 1 AND 128),
    UpdatedAtUtc TEXT NOT NULL
);
