namespace RetroDownfall.Arcanum.Infrastructure.Weave.Comprehension;

/// <summary>Closed first-party single-byte mappings; no ambient encoding provider or platform fallback.</summary>
internal static class SingleByteTextDecoder
{
    public static bool IsSupported(int codePage) => codePage is 1252 or 1251 or 28591;

    public static char Decode(byte value, int codePage)
    {
        if (!IsSupported(codePage))
        {
            throw new InvalidDataException("Unsupported document codepage.");
        }

        if (value < 128 || codePage == 28591)
        {
            return (char)value;
        }

        return codePage == 1251 ? Windows1251[value - 128] : Windows1252[value - 128];
    }

